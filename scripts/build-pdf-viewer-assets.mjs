// ============================================================
// scripts/build-pdf-viewer-assets.mjs — pdf.js for the in-app PDF viewers
// ============================================================
// Resources PDFs are read inside the website and the app, never handed to
// the browser's own viewer (which offers download). Both render with pdf.js
// (pdfjs-dist, legacy build: plain scripts that older Android WebViews run).
//
//   public/pdfjs/pdf.min.js, pdf.worker.min.js   the website loads these
//   mobile/utils/pdfjs-source.ts                  the app bundles pdf.js as
//                                                 strings, so downloaded PDFs
//                                                 open offline
//
// Run after changing the pdfjs-dist version:  node scripts/build-pdf-viewer-assets.mjs
// ============================================================

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const build = path.join(root, 'node_modules/pdfjs-dist/legacy/build')
const version = JSON.parse(readFileSync(path.join(root, 'node_modules/pdfjs-dist/package.json'), 'utf8')).version

const publicDir = path.join(root, 'public/pdfjs')
mkdirSync(publicDir, { recursive: true })
for (const file of ['pdf.min.js', 'pdf.worker.min.js']) copyFileSync(path.join(build, file), path.join(publicDir, file))

const lib = readFileSync(path.join(build, 'pdf.min.js'), 'utf8')
const worker = readFileSync(path.join(build, 'pdf.worker.min.js'), 'utf8')
writeFileSync(path.join(root, 'mobile/utils/pdfjs-source.ts'), [
  `// Generated by scripts/build-pdf-viewer-assets.mjs from pdfjs-dist ${version} (legacy build). Do not edit.`,
  '// pdf.js (Apache-2.0, Mozilla) as strings, inlined into the in-app PDF viewer so it works offline.',
  `export const PDFJS_VERSION = ${JSON.stringify(version)};`,
  `export const PDFJS_LIB = ${JSON.stringify(lib)};`,
  `export const PDFJS_WORKER = ${JSON.stringify(worker)};`,
  '',
].join('\n'))

console.log(`pdf.js ${version}: public/pdfjs (${Math.round((lib.length + worker.length) / 1024)} KB) and mobile/utils/pdfjs-source.ts`)
