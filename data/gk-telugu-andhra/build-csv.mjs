const rows = Q.map(([subtopic, difficulty, question, [correct, ...wrong], explanation], i) => {
  const slot = i % 4
  const options = [...wrong]
  options.splice(slot, 0, correct)
  return { question, option_a: options[0], option_b: options[1], option_c: options[2], option_d: options[3],
    correct_answer: 'ABCD'[slot], explanation, topic: TOPIC, subtopic, chapter: TOPIC, difficulty }
})

